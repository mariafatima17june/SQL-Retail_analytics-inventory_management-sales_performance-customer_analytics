--4) Analyze inventory of the books to identify out of stock inventory
SELECT
    book_id,
    title,
    genre,
    stock,
    CASE
        WHEN stock = 0 THEN 'Out of Stock'
        WHEN stock <= 10 THEN 'Critical Stock'
        WHEN stock <= 30 THEN 'Low Stock'
        ELSE 'Sufficient Stock'
    END AS stock_status
FROM books
ORDER BY stock ASC;

--5) What are the most popular books in each genre
SELECT b.book_id, b.title, b.stock, COALESCE(SUM(o.quantity),0) AS Order_quantity,  
	b.stock- COALESCE(SUM(o.quantity),0) AS Remaining_Quantity
FROM books b LEFT JOIN orders o ON b.book_id=o.book_id
GROUP BY b.book_id ORDER BY b.book_id;

WITH Book_Sales AS (
    SELECT b.book_id, b.title,b.author,b.genre,SUM(o.quantity) AS total_copies_sold
    FROM books b INNER JOIN orders o ON b.book_id = o.book_id
    GROUP BY
        b.book_id,b.title,b.author, b.genre),
Ranked_Books AS (
    SELECT *,
        ROW_NUMBER() OVER ( PARTITION BY genre ORDER BY total_copies_sold DESC)
		AS book_rank
    FROM Book_Sales
)
SELECT
    genre,book_id,title,author,total_copies_sold,book_rank
FROM Ranked_Books
WHERE book_rank <= 3
ORDER BY genre, book_rank;
