--3)Compare each months revenue with the previous months revenue and calculate percentage growth
WITH Monthly_Sales AS (
    SELECT DATE_TRUNC('month', order_date)::DATE AS sales_month,
        SUM(total_amount) AS monthly_revenue
    FROM orders
    GROUP BY DATE_TRUNC('month', order_date)),
Sales_Comparison AS (
    SELECT sales_month, monthly_revenue,
    LAG(monthly_revenue) OVER (ORDER BY sales_month  ) AS previous_month_revenue
    FROM Monthly_Sales)
SELECT
    sales_month,monthly_revenue, previous_month_revenue,
    ROUND(
        (
            (monthly_revenue - previous_month_revenue)
            / NULLIF(previous_month_revenue, 0)
        ) * 100, 2
    ) AS growth_percentage
FROM Sales_Comparison
ORDER BY sales_month;



--CUSTOMER ANALYSIS
--1)Classify customers based on the number of orders placed.
WITH Customer_Orders AS (
    SELECT customer_id, COUNT(order_id) AS total_orders
    FROM orders
    GROUP BY customer_id)

SELECT
    CASE
        WHEN total_orders = 1 THEN 'One-Time Customer'
        WHEN total_orders > 1 THEN 'Repeat Customer'
    END AS customer_type,
    COUNT(*) AS total_customers
FROM Customer_Orders
GROUP BY
    CASE
        WHEN total_orders = 1 THEN 'One-Time Customer'
        WHEN total_orders > 1 THEN 'Repeat Customer'
    END;


-- 2) List customers who have placed at least 2 orders:
SELECT o.customer_id, c.name, COUNT(o.Order_id) AS ORDER_COUNT
FROM orders o
JOIN customers c ON o.customer_id=c.customer_id
GROUP BY o.customer_id, c.name
HAVING COUNT(Order_id) >=2
ORDER BY ORDER_COUNT DESC;

-- 3)Top three customers in each country
WITH Customer_Spending AS (
    SELECT c.customer_id, c.name,c.country, SUM(o.total_amount) AS total_spent
    FROM customers c
    INNER JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY
        c.customer_id,c.name, c.country),Ranked_Customers AS (
    SELECT
        *, DENSE_RANK() OVER (PARTITION BY country ORDER BY total_spent DESC) 
		AS customer_rank
    FROM Customer_Spending
)
SELECT *
FROM Ranked_Customers
WHERE customer_rank <= 3
ORDER BY country, customer_rank;

-- 4) Find the customer who spent the most on orders.
SELECT c.customer_id, c.name, SUM(o.total_amount) AS Total_Spent
FROM orders o
JOIN customers c ON o.customer_id=c.customer_id
GROUP BY c.customer_id, c.name
ORDER BY Total_spent Desc LIMIT 1;


--5) Customers who have never placed orders
